"""Proposed non-secret context preparation, after path/model selection.

Reads only source and selection. Writes a NEW output directory. Never reads
credentials, runs a provider, creates a container or modifies accepted source.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True


def rel(value):
    if not isinstance(value, str) or not value or any(c in value for c in ('\n', '\0', '\\')):
        raise ValueError('explicit relative path required')
    p = Path(value)
    if p.is_absolute() or any(x in ('', '.', '..') for x in value.split('/')):
        raise ValueError('unsafe relative path')
    return value


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('selection'); p.add_argument('source'); p.add_argument('manifest'); p.add_argument('output')
    a = p.parse_args(); s = json.loads(Path(a.selection).read_text())
    from render_commands import render
    render(s, 'live')  # Refuse unresolved inputs before touching output.
    source = Path(a.source).resolve()
    pins = json.loads((Path(__file__).parent / 'checkpoint-files.json').read_text())
    inputs_pin = json.loads((Path(__file__).parent / 'inputs.json').read_text())
    if hashlib.sha256((Path(__file__).parent / 'checkpoint-files.json').read_bytes()).hexdigest() != inputs_pin['checkpoint_files_sha256']:
        raise SystemExit('checkpoint file inventory changed')
    if pins['checkpoint'] != s['source_checkpoint']:
        raise SystemExit('wrong source checkpoint')
    for row in pins['files']:
        path = source / row['path']
        if path.is_symlink():
            raise SystemExit('source symlink refused')
        raw_source = path.read_bytes()
        blob = hashlib.sha1(b'blob ' + str(len(raw_source)).encode() + b'\0' + raw_source).hexdigest()
        if blob != row['git_blob']:
            raise SystemExit('checkpoint blob mismatch: ' + row['path'])
    if list((source / 'v12').rglob('*.pyc')):
        raise SystemExit('export must have no generated bytecode')
    manifest = json.loads(Path(a.manifest).read_text())
    material = {k: manifest[k] for k in ('base', 'files')}
    identity = 'sha256:' + hashlib.sha256(json.dumps(material, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    if identity != s['accepted_candidate']:
        raise SystemExit('wrong accepted candidate')
    for row in manifest['files']:
        if hashlib.sha256((source / row['path']).read_bytes()).hexdigest() != row['sha256']:
            raise SystemExit('accepted file mismatch: ' + row['path'])
    # Exact base export must separately pass the operator source preflight;
    # the delta manifest alone does not attest unchanged base files.
    sys.path[:0] = [str(source / 'v12/worker'), str(source / 'v12/python/src/baton_v12')]
    import provider_policy as policy
    from codex_agent import CodexAgent
    instruction = rel(s['instruction_relative_to_home'])
    code_home = rel(s['codex_home_relative_to_home'])
    credential = code_home + '/' + rel(s['credential_relative_path'])
    if instruction == credential or instruction.startswith(credential + '/') or credential.startswith(instruction + '/'):
        raise SystemExit('instruction/credential overlap')
    raw = policy.worker_instructions()
    expected = (Path(__file__).parent / 'inputs.json')
    inputs = json.loads(expected.read_text())
    if hashlib.sha256(raw).hexdigest() != inputs['worker_instructions_sha256']:
        raise SystemExit('wrong packaged instructions')
    sha = 'sha256:' + hashlib.sha256(raw).hexdigest()
    # Qualification envelope only; do not install REALIZATIONS or MANAGED.
    # This calls the SAME accepted label functions, not adapter() or native Job admission.
    doc = dict(provider='codex', home='/run/baton/provider-home',
               context_label=policy._context_label('codex'),
               managed_entries=[dict(path=instruction, kind=policy.INSTRUCTIONS_KIND, sha256=sha, bytes=len(raw))])
    task = ('Qualification-only task, no product repository and no native Job acceptance. '
            'Act only as implementation. Read the delivered worker instruction file named above. '
            'Use a local read/hash tool to compute its SHA-256. Do not inspect auth, session stores, '
            'environment values, other home files, or any network resource. Do not delegate or edit files. '
            'Reply once with qualification_probe=complete, your assigned role, and the computed '
            'worker_instructions_sha256, its byte length, and its exact first line. Compute these from '
            'the delivered file, not from the label. State any inability honestly. Do not claim a model identity.')
    prompt = policy.labelled(doc, 'implementation', task)
    agent = CodexAgent.__new__(CodexAgent)
    argv = agent.provider_argv(prompt, model=s['explicit_model'], service_tier=s.get('service_tier'))
    out = Path(a.output); out.mkdir(parents=False, exist_ok=False)
    (out / 'worker_instructions.md').write_bytes(raw)
    (out / 'prompt.txt').write_text(prompt)
    (out / 'live-context.json').write_text(json.dumps(dict(qualification_only=True,
        authorization=s['authorization_live'], source_checkpoint=s['source_checkpoint'],
        service_tier={"requested": s.get("service_tier"), "observed": None},
        login_status_help_evidence=s['login_status_help_evidence'],
        tool_inventory_evidence=s['tool_inventory_evidence'], image_tool_decision=s['image_tool_decision'], codex_home=doc['home'] + '/' + code_home,
        instruction_relative_to_home=instruction, argv=argv,
        context_record=policy.context_record(doc, 'implementation'),
        envelope=doc, candidate=identity), indent=2) + '\n')
