    def written_runtime_root(self):
        place = self.packet_root / "runtime"
        place.mkdir(exist_ok=True)
        (place / "baton-v12-stack").write_bytes(b"#!/bin/sh\nexit 0\n")
        return str(place)

    def written_manager_source(self):
        """A REAL importable tree, bound file by file, and a SMALL one.

        The production packet binds `baton_v12` and `tools`. Binding this
        checkout's `v12/python` here instead would hash every transient
        scratch directory the test process creates under it, so what this
        exercises is the composer's file-by-file binding rather than the size
        of the tree it is pointed at. `test_baseline` covers the import-
        location refusal that the production binding exists for.
        """
        place = self.packet_root / "manager-source"
        (place / "boundpkg").mkdir(parents=True, exist_ok=True)
        (place / "boundpkg" / "__init__.py").write_text(
            "VERSION = 'bound'\n", encoding="utf-8")
        return str(place)

    def generate(self):
        """Compose and WRITE the packet, exactly as the operator command does."""
        if self.generated is None:
            self.run_root = os.path.join(self.root, "generated-run")
            documents = baseline_bindings.compose(
                base=self.base, run_root=self.run_root, **self.selections())
            places = baseline_bindings.write(self.run_root, documents,
                                             checkout=self.checkout)
            # THE CERTIFIED PROFILE IS THE GENERATED ONE, and so is the
            # submission: every stage is compared against the Job's single
            # input digest and against the worker's configured policy and
            # profile, so a submission composed from the accepted fixture's
            # manifest could be served by no worker this deployment configures.
            if "context-profile.json" in documents:
                self.context_profile = documents["context-profile.json"]
                self.context_digest = digest(self.context_profile)
            self.submission = documents["submission.json"]
            self.generated = (documents, places)
        return self.generated

    def composed_document(self, **members):
        """THE GENERATED DEPLOYMENT, not the accepted test fixture's.

        This is the substitution the whole case exists to make: everything
        downstream -- the preflight, the sessions, the pool, the launch
        documents, the mounts and the endings -- reads bytes
        `baseline_bindings` produced.
        """
        del members
        documents, _places = self.generate()
        return documents["deployment.json"]

    def turn(self, control, role, attempt_id, roots, **operands):
        """One worker turn, adopted from the GENERATED launch home."""
        documents, _places = self.generate()
        workers = {one["role"]: one["deployment"]
                   for one in documents["deployment.json"]["workers"]}
        held = self.config["launch_home"]
        self.config["launch_home"] = workers[role]["launch_home"]
        try:
            return super().turn(control, role, attempt_id, roots, **operands)
        finally:
            self.config["launch_home"] = held

    def packet_for(self):
        """The generated `PACKET.json`, adapted to this case's own context.

        Two members are this fixture's rather than the composer's: the context
        profile the accepted harness certifies, and the submission the
        supervised case submits. Everything else -- the bounds, the fixture
        binding, the manager source, the deployment path and digest -- is the
        generated packet's own.
        """
        _documents, places = self.generate()
        packet = json.loads(Path(places["PACKET.json"]).read_text(
            encoding="utf-8"))
        if packet["schema"] == baseline.PACKET_SCHEMA:
            packet["context"].update(
                profile_path=str(self.packet_root / "profile.json"),
                profile_sha256=self.digest_of(str(self.packet_root
                                                  / "profile.json")),
                profile_digest=self.context_digest,
                storage_path=str(self.context_root))
        packet["submission"] = dict(
            packet["submission"],
            path=str(self.packet_root / "submission.json"),
            sha256=self.digest_of(str(self.packet_root / "submission.json")))
        packet["deployment"].update(
            job_store=str(Path(self.root) / "jobs.sqlite3"),
            control_store=str(Path(self.root) / "control.sqlite3"),
            authority_store=str(self.authority_path),
            authority_uuid=self.config["authority_uuid"],
            state_root=str(self.root))
        packet["outcome_path"] = str(self.packet_root
                                     / "generated-outcome.json")
        place = self.packet_root / "GENERATED-PACKET.json"
        place.write_text(json.dumps(packet, sort_keys=True, indent=2),
                         encoding="utf-8")
        self.generated_packet_path = str(place)
        return packet

    # -- the whole path, in one run -----------------------------------------

    def test_the_generated_deployment_produces_one_attributed_proposal(self):
        packet = self.packet_for()
        _composed, outcome, _job, _control = self.supervised(packet=packet)
