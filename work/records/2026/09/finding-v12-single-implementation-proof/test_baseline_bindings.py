"""The GENERATED single-implementation packet, driven through real boundaries.

WHAT IS REAL HERE. `baseline_bindings.compose` and `write` produce the
deployment, the sealed input manifest, the candidate context profile, the
submission and `PACKET.json`; `stage_execution.held_configuration` and
`operations_from` read THOSE bytes; and `baseline.supervise` drives them
through `held_packet`, the owner acts, the admission gate, the real worker
turn, the cancellation seam, the ending driver and the cleanup accounting. The
Authority is a fresh disposable one built through public APIs, which is
ordinary deterministic fixture setup and touches no deployed instance.

WHAT IS NOT CLAIMED. The engine and the provider subprocess remain the two
accepted deterministic seams. No container, no image, no live provider, no
network, no credential, and no operator deployment is read or changed.

WHY COMPOSITION IS CHECKED HERE AND NOT ONLY DESCRIBED. W236087's packet was
validated document by document and then produced a live run whose shape nobody
had exercised end to end. The composition cases below assert the three
decisions the split ruling actually made -- one submitted stage, one admitted
container, and no review vocabulary in the run's own outcome -- and the driving
case then runs those exact bytes.

A REVIEW WORKER IS STILL CONFIGURED, because `stage_execution` refuses a
deployment that names none: "a Job that cannot be produced or independently
reviewed serves nothing". Deleting it to make this Job look smaller would be
relaxing an independence invariant to pass a validator. So what the driving
case establishes is the stronger statement -- a reviewer was configured and
launchable, and this run started exactly one container anyway.
"""
