"""The two OPERATOR ENTRYPOINTS, run as documented. W239528 R1.

Review 2026-09-22T15:32:51Z: "OPERATOR-239528.md steps 3 and 5 invoke plain
`python3` without binding the interpreter, import path or working directory. In
a child with no implicit PYTHONPATH, the documented composer command fails at
its first product import with `ModuleNotFoundError: No module named
'baton_v12'`... Validate the composer and supervisor entrypoint with a
disposable, relocated real source tree and generated bytes."

That reproduction is correct and this file is the answer to it. Two things were
missing and both are here:

  * `baseline_bindings.main` had never been executed as the operator executes
    it -- a child process, with an explicit interpreter and an explicit import
    path, and nothing inherited from a developer shell. `TheDocumentedComposer`
    runs the exact command `OPERATOR-239528.md` now prints, in a child whose
    `PYTHONPATH` is set to the bound source and to nothing else, over a
    RELOCATED copy of the real `baton_v12` and `tools` -- the flattened layout
    a deployed manager source actually has, which is the layout that makes one
    `PYTHONPATH` entry sufficient.
  * `baseline.main` had never been executed at all. The composition cases call
    `supervise` directly, so `main`'s own path -- the packet proving, the
    import binding, the engine question, the Job survey, opening both stores,
    the owner acts, composing the deployment and the exit status -- was
    uncovered. `TheDocumentedSupervisor` drives it.

WHAT IS RELOCATED AND WHAT IS IMPORTED, because they are deliberately not the
same tree. The composer child imports from the relocated copy, which is what a
deployed operator does. The supervisor case runs IN THIS PROCESS, so the tree
it must bind is the one this process really imports -- `verify_imported_sources`
compares the imported packages' resolved locations against the bound source,
and binding anything else would make it pass for the wrong reason or refuse for
one. The relocated copy is therefore used a second way in the supervisor case:
as the packet a correct `main` REFUSES, before opening any store.

THE TWO DETERMINISTIC SEAMS STAY WHERE THEY ARE. `baseline.main` already takes
`compose` and `image_inspect` for a deployment to supply, and `time.sleep` is
patched because the composed deployment has no daemon to run a container. No
container, image, live provider, network, credential or deployed store is
reached.
"""
