class TheLiveRunShapeIsReportedHonestly(TheGeneratedPacketDrivesTheRealEntrypoint):
    """The first live run's shape, over generated bytes. LIVE-RUN-239365.md.

    One implementation runtime starts and its turn fails; the review stage
    never leaves `blocked`, and it carries an episode identity the status
    projection reports but for which no runtime was ever allocated. The live
    run counted that identity as a started runtime and produced three
    held-reasons about it, which buried the one real failure.

    THE STOP REASON DIFFERS FROM THE LIVE RUN'S and that is not the subject
    here: a failed turn in this harness leaves the stage waiting rather than
    reaching an ending, so the run stops at its own bound instead of at
    `exceptional`. What is under test is the CLASSIFICATION, which is the same
    either way -- one runtime started, one identity never allocated.
    """

    def driver(self, job, control, composed, **operands):
        del operands

        def wait(seconds):
            del seconds
            if self.states(job, composed).get("implementation") == "waiting":
                attempt = self.pending(composed, "implementation")
                if attempt is None:
                    return None
                self.turned.add(attempt)
                # THE TURN FAILS. What the live provider did was answer with a
                # review verdict and publish no proposal; either way the
                # implementation contract is unsatisfied and the stage ends
                # exceptional, which is the shape under test here.
                return self.turn(
                    control, "implementation", attempt,
                    self.mounted(composed, "implementation", attempt),
                    status=1)
            return None
        return wait

    def bounded(self):
        packet = dict(self.packet_for(), bounds=dict(
            self.packet["bounds"], total_seconds=12, cleanup_seconds=3))
        return self.supervised(packet=packet)

    def test_a_never_allocated_episode_is_named_and_not_charged_cleanup(self):
        _composed, outcome, _job, _control = self.bounded()
        self.assertEqual(outcome["state"], "held")
        self.assertEqual(outcome["admissions"],
                         {"implementation": 1, "review": 0})
