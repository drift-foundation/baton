    def main_packet(self, **bounds):
        """The generated packet, bound to the source this process imports."""
        packet = self.packet_for()
        packet["manager_source"] = self.imported_source()
        # THE CODE BOUNDARY IS `tools/`, the tree whose `__file__` the inferred
        # boundary was derived from and the one this correction exists about.
        # The fixture's disk-backed roots are siblings of `src/` and `tools/`,
        # not inside either, which is the same shape a relocated manager source
